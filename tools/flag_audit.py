#!/usr/bin/env python3
"""Story flags that are set but never read (2026-11-10). Counts every word-match of the flag's name in the scripts
and tools, comments stripped (so flags read through %i[...] lists, hash keys and dialogue conditions count), minus
its set_flag calls.

    python3 tools/flag_audit.py [--md docs/review/FLAGS_UNREAD.md]"""
import sys
import re, glob, collections
files = glob.glob('game/Data/Scripts/998_FrostThaw/*.rb') + glob.glob('tools/*.rb')
src = {f: open(f, encoding='utf-8', errors='ignore').read() for f in files}
# strip comments
code = {f: "\n".join(re.sub(r'\s#\s.*$', '', l) if not l.strip().startswith('#') else '' for l in s.split("\n")) for f, s in src.items()}
allc = "\n".join(code.values())
sets = collections.defaultdict(list)
for f, s in code.items():
    for m in re.finditer(r'set_flag\(\s*:(\w+)', s):
        sets[m.group(1)].append("%s:%d" % (f.split('/')[-1], s.count("\n", 0, m.start()) + 1))
dead = []
for fl, locs in sorted(sets.items()):
    words = len(re.findall(r'(?<![\w])%s(?![\w])' % re.escape(fl), allc))
    setn = len(re.findall(r'set_flag\(\s*:%s(?![\w])' % re.escape(fl), allc))
    if words - setn <= 0:
        dead.append((fl, locs))
print(len(sets), "flags set;", len(dead), "never read")
for fl, locs in dead: print(fl, " ".join(locs[:3]))
if "--md" in sys.argv:
    out = sys.argv[sys.argv.index("--md") + 1]
    with open(out, "w") as fh:
        fh.write("# Story flags set but never read\n\n")
        fh.write("Generated by `tools/flag_audit.py` on 2026-11-10: %d flags are set, %d of them are never read.\n\n" % (len(sets), len(dead)))
        fh.write("All of them are **records**: the choice they mark plays out in full in the scene that sets it (a line, a\n"
                 "fight, a gift, a door), and nothing later depends on it. None gates anything, so none can strand the player.\n"
                 "They stay in place rather than being removed: each is a cheap hook for a later payoff (an epilogue line, a\n"
                 "callback), and removing them gains nothing. The ones that deserved a payoff got one in 0.8.5 (the epilogue's\n"
                 "rootbeasts_freed, sporelings_saved, rose_to_frostina and selrae_sentenced lines).\n\n")
        fh.write("| flag | set at |\n|---|---|\n")
        for fl, locs in dead:
            fh.write("| `%s` | %s |\n" % (fl, ", ".join(locs[:3])))

