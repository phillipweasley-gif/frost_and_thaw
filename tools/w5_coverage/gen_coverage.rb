# Writes docs/coverage_W5.md: every row of W5's slice of the audits, its status
# now, where it is (file:line, map id) and the test that covers it.
R = File.expand_path("../..", __dir__)
FT = "#{R}/game/Data/Scripts/998_FrostThaw"
SRC = Dir["#{FT}/*.rb"].to_h { |f| [File.basename(f), File.readlines(f, encoding: "UTF-8")] }
TOOLS = Dir["#{R}/tools/build_ch6.rb", "#{R}/tools/build_ch6b.rb", "#{R}/tools/build_rootspire_life.rb"].to_h { |f| [File.basename(f), File.readlines(f, encoding: "UTF-8")] }
SHORT = { "A" => "048_Rootspire_A_City.rb", "B" => "048_Rootspire_B_People.rb", "C" => "048_Rootspire_C_Folk.rb",
          "D" => "048_Rootspire_D_Quests.rb", "E" => "048_Rootspire_E_Nights.rb", "F" => "048_Rootspire_F_Downtime.rb",
          "G" => "048_Rootspire_G_Hooks.rb", "024" => "024_Chapter6.rb", "026" => "026_Rootspire.rb" }

# "D.heist_ward" -> 048_Rootspire_D_Quests.rb:812 ; "E/night_" text search ; "map:2198" ; "build:Smuggler" (builder line)
def ref(r)
  case r
  when /\Amap:(.+)\z/ then "map #{$1}"
  when /\Abuild:(\w+):(.+)\z/
    f, text = { "6" => "build_ch6.rb", "6b" => "build_ch6b.rb", "life" => "build_rootspire_life.rb" }[$1], $2
    i = TOOLS[f].index { |l| l.include?(text) } or raise "builder ref #{r}"
    "tools/#{f}:#{i + 1}"
  when /\A(\w+)\.(\w+[?!]?)\z/
    f, name = SHORT[$1], $2
    rx = /^\s*def (self\.)?#{Regexp.escape(name)}\b/
    i = SRC[f].index { |l| l =~ rx } or raise "no def #{r}"
    "#{f}:#{i + 1}"
  when /\A(\w+)\/(.+)\z/
    f, text = SHORT[$1], $2
    i = SRC[f].index { |l| l.include?(text) } or raise "no text #{r}"
    "#{f}:#{i + 1}"
  else r
  end
end

load "#{__dir__}/coverage_rows.rb"     # ROWS = { "audit:line" => [status, [refs], test] }

AUDITS = { "A" => "A_session_log.md", "B" => "B_rootspire_tab1.md", "C" => "C_rootspire_tab2_forge.md", "D" => "D_rootspire_tabs3to8.md" }
out = []
out << "# Coverage: W5 (Rootspire as a living city, and Chapter 6)"
out << ""
out << "Every row of W5's slice of the audits, what it is now, where it is, and what tests it."
out << "Generated by `tools/w5_coverage/gen_coverage.rb` from `tools/w5_coverage/coverage_rows.rb` (file:line resolved from the code at commit time)."
out << ""
out << "Tests: **city** = `tools/headless/try_w5_city.rb` and **quests** = `tools/headless/try_w5_quests.rb` (play the quests in the real game), **sweep** ="
out << "`tools/headless/try_w5_sweep.rb` (talks to every event on the W5 maps in three story states, plays every"
out << "night event, omen, vignette and downtime day, and each Herald's days in Herald Mode, failing on any script error),"
out << "**smoke** = `tests/smoke_test.rb`, **maps** = `tools/check_all.rb`. \"Outside W5\" rows are in another worker's"
out << "slice (named); they are listed so the slice is complete."
out << ""
counts = Hash.new(0)
AUDITS.each do |key, file|
  lines = File.readlines("#{R}/docs/audit/#{file}", encoding: "UTF-8")
  rows = ROWS.select { |k, _| k.start_with?("#{key}:") }
  next if rows.empty?
  out << "## #{file}"
  out << ""
  out << "| Audit line | Item | Audit said | Status now | Where | Test |"
  out << "|---|---|---|---|---|---|"
  rows.sort_by { |k, _| k.split(":")[1].to_i }.each do |k, (status, refs, test)|
    n = k.split(":")[1].to_i
    c = lines[n - 1].split("|").map(&:strip)
    raise "row #{k} is not a table row: #{lines[n - 1][0, 60]}" if !lines[n - 1].start_with?("| ")
    numbered = (key == "C" || key == "D")
    next if numbered && c[1] !~ /\A\d+\z/          # a section heading inside the table
    item, was, where = numbered ? [c[2], c[4], c[5]] : [c[1], c[3], c[4]]
    counts[status.start_with?("Changed (approved)") ? "Changed (approved)" : status.split(" (").first.split(":").first] += 1
    refs = refs.map { |r| r == :audit ? "as audited: #{where}" : ref(r) }
    out << "| #{n} | #{item.gsub('|', '/')} | #{was} | #{status} | #{refs.join('; ')} | #{test} |"
  end
  out << ""
end
out.insert(out.index { |l| l.start_with?("## ") }, "Totals: " + counts.sort_by { |k, _| k }.map { |k, v| "#{k} #{v}" }.join(", "), "")
out << File.read("#{__dir__}/notes.md")
File.write("#{R}/docs/coverage_W5.md", out.join("\n") + "\n")
puts "wrote #{ROWS.size} rows: #{counts.inspect}"
